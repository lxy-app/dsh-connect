package store

import (
	"context"
	"fmt"
	"time"

	"github.com/deepseek/dsh-connect/server/ent"
	"github.com/deepseek/dsh-connect/server/ent/mobiledevice"
	"github.com/deepseek/dsh-connect/server/ent/mobilepairingcode"
	"github.com/deepseek/dsh-connect/server/ent/user"
	"github.com/deepseek/dsh-connect/server/internal/protocol"
)

// MobileDeviceRecord couples the public mobile device projection with its
// credential hashes. Plaintext tokens never leave the HTTP response that
// created them.
type MobileDeviceRecord struct {
	Device           protocol.MobileDevice
	AccessTokenHash  string
	RefreshTokenHash string
	AccessExpiresAt  *time.Time
	RefreshExpiresAt *time.Time
}

// MobileCredential is generated by the HTTP layer and written atomically during
// pairing or refresh-token rotation.
type MobileCredential struct {
	AccessTokenHash  string
	RefreshTokenHash string
	AccessExpiresAt  time.Time
	RefreshExpiresAt time.Time
}

// MobilePairingCode stores a one-time code for a specific user. Only the hash is
// persisted.
type MobilePairingCode struct {
	CodeHash  string
	UserID    string
	CreatedAt time.Time
	ExpiresAt time.Time
}

// CreateMobilePairingCode inserts a one-time code hash.
func (s *Store) CreateMobilePairingCode(ctx context.Context, code MobilePairingCode) error {
	if _, err := s.client.MobilePairingCode.Create().
		SetCodeHash(code.CodeHash).
		SetUserID(code.UserID).
		SetCreatedAt(code.CreatedAt).
		SetExpiresAt(code.ExpiresAt).
		Save(ctx); err != nil {
		return fmt.Errorf("create mobile pairing code: %w", err)
	}
	return nil
}

// RedeemMobilePairingCode atomically consumes a code, creates the mobile device
// and binds its first access/refresh token pair. The target user comes from the
// stored code, never from the client request.
func (s *Store) RedeemMobilePairingCode(
	ctx context.Context,
	codeHash string,
	device MobileDeviceRecord,
	credential MobileCredential,
	now time.Time,
) (MobileDeviceRecord, User, error) {
	tx, err := s.client.Tx(ctx)
	if err != nil {
		return MobileDeviceRecord{}, User{}, fmt.Errorf("begin mobile pairing transaction: %w", err)
	}
	defer func() { _ = tx.Rollback() }()

	code, err := tx.MobilePairingCode.Query().
		Where(mobilepairingcode.CodeHash(codeHash)).
		Only(ctx)
	if ent.IsNotFound(err) {
		return MobileDeviceRecord{}, User{}, ErrPairingCodeInvalid
	}
	if err != nil {
		return MobileDeviceRecord{}, User{}, fmt.Errorf("load mobile pairing code: %w", err)
	}
	if code.UsedAt != nil {
		return MobileDeviceRecord{}, User{}, ErrPairingCodeUsed
	}
	if !now.Before(code.ExpiresAt) {
		return MobileDeviceRecord{}, User{}, ErrPairingCodeExpired
	}

	userRecord, err := tx.User.Query().Where(user.IDEQ(code.UserID)).Only(ctx)
	if ent.IsNotFound(err) {
		return MobileDeviceRecord{}, User{}, ErrUserNotFound
	}
	if err != nil {
		return MobileDeviceRecord{}, User{}, fmt.Errorf("load mobile pairing user: %w", err)
	}
	if userRecord.Status != user.StatusActive {
		return MobileDeviceRecord{}, User{}, ErrUserDisabled
	}

	created, err := tx.MobileDevice.Create().
		SetID(device.Device.MobileDeviceID).
		SetUserID(code.UserID).
		SetDeviceName(device.Device.DeviceName).
		SetPlatform(mobiledevice.Platform(device.Device.Platform)).
		SetAppVersion(device.Device.AppVersion).
		SetStatus(mobiledevice.StatusActive).
		SetAccessTokenHash(credential.AccessTokenHash).
		SetRefreshTokenHash(credential.RefreshTokenHash).
		SetAccessExpiresAt(credential.AccessExpiresAt).
		SetRefreshExpiresAt(credential.RefreshExpiresAt).
		SetCreatedAt(device.Device.CreatedAt).
		SetUpdatedAt(device.Device.UpdatedAt).
		SetLastSeenAt(now).
		Save(ctx)
	if err != nil {
		return MobileDeviceRecord{}, User{}, fmt.Errorf("create mobile device: %w", err)
	}

	// A conditional update guarantees the code is consumed exactly once even
	// when two phones race on the same code. The losing transaction rolls back
	// its mobile device row.
	updated, err := tx.MobilePairingCode.Update().
		Where(mobilepairingcode.IDEQ(code.ID), mobilepairingcode.UsedAtIsNil()).
		SetUsedAt(now).
		SetMobileDeviceID(created.ID).
		Save(ctx)
	if err != nil {
		return MobileDeviceRecord{}, User{}, fmt.Errorf("consume mobile pairing code: %w", err)
	}
	if updated == 0 {
		return MobileDeviceRecord{}, User{}, ErrPairingCodeUsed
	}
	persisted := toMobileDeviceRecord(created)
	pairedUser := toUser(userRecord)
	if err := tx.Commit(); err != nil {
		return MobileDeviceRecord{}, User{}, fmt.Errorf("commit mobile pairing transaction: %w", err)
	}
	return persisted, pairedUser, nil
}

// AuthenticateMobileAccess resolves a short-lived access token and verifies
// that both the device and its owning user remain active.
func (s *Store) AuthenticateMobileAccess(ctx context.Context, tokenHash string, now time.Time) (MobileDeviceRecord, User, error) {
	record, err := s.client.MobileDevice.Query().
		Where(
			mobiledevice.AccessTokenHash(tokenHash),
			mobiledevice.AccessTokenHashNEQ(""),
			mobiledevice.StatusEQ(mobiledevice.StatusActive),
		).
		Only(ctx)
	if ent.IsNotFound(err) {
		return MobileDeviceRecord{}, User{}, ErrMobileSessionInvalid
	}
	if err != nil {
		return MobileDeviceRecord{}, User{}, fmt.Errorf("load mobile session: %w", err)
	}
	if record.AccessExpiresAt == nil || !now.Before(*record.AccessExpiresAt) {
		return MobileDeviceRecord{}, User{}, ErrMobileSessionInvalid
	}
	userRecord, err := s.client.User.Query().Where(user.IDEQ(record.UserID)).Only(ctx)
	if ent.IsNotFound(err) {
		return MobileDeviceRecord{}, User{}, ErrMobileSessionInvalid
	}
	if err != nil {
		return MobileDeviceRecord{}, User{}, fmt.Errorf("load mobile session user: %w", err)
	}
	if userRecord.Status != user.StatusActive {
		return MobileDeviceRecord{}, User{}, ErrMobileSessionInvalid
	}
	return toMobileDeviceRecord(record), toUser(userRecord), nil
}

// RotateMobileRefresh atomically replaces both tokens. Using the previous
// refresh token after a successful rotation fails; concurrent rotations have
// exactly one winner.
func (s *Store) RotateMobileRefresh(
	ctx context.Context,
	refreshTokenHash string,
	credential MobileCredential,
	now time.Time,
) (MobileDeviceRecord, User, error) {
	tx, err := s.client.Tx(ctx)
	if err != nil {
		return MobileDeviceRecord{}, User{}, fmt.Errorf("begin mobile refresh transaction: %w", err)
	}
	defer func() { _ = tx.Rollback() }()

	record, err := tx.MobileDevice.Query().
		Where(
			mobiledevice.RefreshTokenHash(refreshTokenHash),
			mobiledevice.RefreshTokenHashNEQ(""),
			mobiledevice.StatusEQ(mobiledevice.StatusActive),
		).
		Only(ctx)
	if ent.IsNotFound(err) {
		return MobileDeviceRecord{}, User{}, ErrMobileSessionInvalid
	}
	if err != nil {
		return MobileDeviceRecord{}, User{}, fmt.Errorf("load mobile refresh session: %w", err)
	}
	if record.RefreshExpiresAt == nil || !now.Before(*record.RefreshExpiresAt) {
		return MobileDeviceRecord{}, User{}, ErrMobileSessionInvalid
	}
	userRecord, err := tx.User.Query().Where(user.IDEQ(record.UserID)).Only(ctx)
	if ent.IsNotFound(err) {
		return MobileDeviceRecord{}, User{}, ErrMobileSessionInvalid
	}
	if err != nil {
		return MobileDeviceRecord{}, User{}, fmt.Errorf("load mobile refresh user: %w", err)
	}
	if userRecord.Status != user.StatusActive {
		return MobileDeviceRecord{}, User{}, ErrMobileSessionInvalid
	}

	updated, err := tx.MobileDevice.Update().
		Where(
			mobiledevice.IDEQ(record.ID),
			mobiledevice.RefreshTokenHash(refreshTokenHash),
			mobiledevice.StatusEQ(mobiledevice.StatusActive),
		).
		SetAccessTokenHash(credential.AccessTokenHash).
		SetRefreshTokenHash(credential.RefreshTokenHash).
		SetAccessExpiresAt(credential.AccessExpiresAt).
		SetRefreshExpiresAt(credential.RefreshExpiresAt).
		SetLastSeenAt(now).
		SetUpdatedAt(now).
		Save(ctx)
	if err != nil {
		return MobileDeviceRecord{}, User{}, fmt.Errorf("rotate mobile refresh token: %w", err)
	}
	if updated == 0 {
		return MobileDeviceRecord{}, User{}, ErrMobileSessionInvalid
	}
	persisted, err := tx.MobileDevice.Query().Where(mobiledevice.IDEQ(record.ID)).Only(ctx)
	if err != nil {
		return MobileDeviceRecord{}, User{}, fmt.Errorf("reload mobile refresh session: %w", err)
	}
	if err := tx.Commit(); err != nil {
		return MobileDeviceRecord{}, User{}, fmt.Errorf("commit mobile refresh transaction: %w", err)
	}
	return toMobileDeviceRecord(persisted), toUser(userRecord), nil
}

// RevokeMobileDevice invalidates all mobile credentials while retaining the row
// for audit and administrative visibility.
func (s *Store) RevokeMobileDevice(ctx context.Context, mobileDeviceID string, now time.Time) error {
	affected, err := s.client.MobileDevice.Update().
		Where(mobiledevice.IDEQ(mobileDeviceID)).
		SetStatus(mobiledevice.StatusRevoked).
		SetAccessTokenHash("").
		SetRefreshTokenHash("").
		ClearAccessExpiresAt().
		ClearRefreshExpiresAt().
		SetRevokedAt(now).
		SetUpdatedAt(now).
		Save(ctx)
	if err != nil {
		return fmt.Errorf("revoke mobile device: %w", err)
	}
	if affected == 0 {
		return ErrMobileDeviceNotFound
	}
	return nil
}

// MobileDeviceByID loads a paired phone for desktop-side access review.
func (s *Store) MobileDeviceByID(ctx context.Context, mobileDeviceID string) (MobileDeviceRecord, error) {
	record, err := s.client.MobileDevice.Query().
		Where(mobiledevice.IDEQ(mobileDeviceID)).
		Only(ctx)
	if ent.IsNotFound(err) {
		return MobileDeviceRecord{}, ErrMobileDeviceNotFound
	}
	if err != nil {
		return MobileDeviceRecord{}, fmt.Errorf("load mobile device: %w", err)
	}
	return toMobileDeviceRecord(record), nil
}

// MobileDevices lists paired phones, newest first.
func (s *Store) MobileDevices(ctx context.Context) ([]MobileDeviceRecord, error) {
	records, err := s.client.MobileDevice.Query().
		Order(ent.Desc(mobiledevice.FieldCreatedAt)).
		All(ctx)
	if err != nil {
		return nil, fmt.Errorf("list mobile devices: %w", err)
	}
	result := make([]MobileDeviceRecord, 0, len(records))
	for _, record := range records {
		result = append(result, toMobileDeviceRecord(record))
	}
	return result, nil
}

func toMobileDeviceRecord(record *ent.MobileDevice) MobileDeviceRecord {
	return MobileDeviceRecord{
		Device: protocol.MobileDevice{
			MobileDeviceID: record.ID,
			UserID:         record.UserID,
			DeviceName:     record.DeviceName,
			Platform:       string(record.Platform),
			AppVersion:     record.AppVersion,
			Status:         string(record.Status),
			CreatedAt:      record.CreatedAt,
			UpdatedAt:      record.UpdatedAt,
			LastSeenAt:     record.LastSeenAt,
			RevokedAt:      record.RevokedAt,
		},
		AccessTokenHash:  record.AccessTokenHash,
		RefreshTokenHash: record.RefreshTokenHash,
		AccessExpiresAt:  record.AccessExpiresAt,
		RefreshExpiresAt: record.RefreshExpiresAt,
	}
}
